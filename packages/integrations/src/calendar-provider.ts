/** SDD-08 / v0.3: application-facing calendar capability, independent of Google. */
export interface CalendarContext {
  readonly tenantId: string;
  /** Resolved from the tenant's connected integration, never a client choice. */
  readonly calendarId: string;
  /** Short-lived credential supplied by an infrastructure credential resolver. */
  readonly accessToken: string;
}

/** Resolves one tenant's connected calendar without trusting a client token. */
export interface CalendarConnectionResolver {
  resolve(tenantId: string, integrationId: string): Promise<CalendarContext>;
}

export interface CalendarInterval {
  readonly startsAt: Date;
  readonly endsAt: Date;
}

export interface AvailabilityInput extends CalendarContext, CalendarInterval {}

export interface AvailabilityResult {
  /** Busy intervals; the booking service must intersect these with business hours. */
  readonly busy: readonly CalendarInterval[];
}

export interface CreateCalendarAppointmentInput extends CalendarContext, CalendarInterval {
  /** UUID generated by the local Appointment row before the provider call. */
  readonly appointmentId: string;
  readonly title: string;
  readonly description?: string;
  readonly timeZone: string;
}

export interface CalendarAppointmentResult {
  readonly providerEventId: string;
  readonly startsAt: Date;
  readonly endsAt: Date;
}

export interface CancelCalendarAppointmentInput extends CalendarContext {
  readonly providerEventId: string;
}

export interface CalendarProvider {
  getAvailability(input: AvailabilityInput): Promise<AvailabilityResult>;
  createAppointment(input: CreateCalendarAppointmentInput): Promise<CalendarAppointmentResult>;
  cancelAppointment(input: CancelCalendarAppointmentInput): Promise<void>;
}

/** Safe for logs: never contains tokens, request bodies, or provider response text. */
export class CalendarProviderError extends Error {
  override readonly name = 'CalendarProviderError';

  constructor(
    readonly code: string,
    readonly retryable: boolean,
  ) {
    super(`Calendar provider operation failed: ${code}`);
  }
}
